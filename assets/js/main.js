/* ═══════════════════════════════════════════════════════════════
   [STUDIO_NAME] — interaction layer (vanilla JS, no dependencies)
   Loaded as an external file so a strict CSP (script-src 'self') works.
   Everything here is progressive enhancement: the page works without JS.
   ═══════════════════════════════════════════════════════════════ */
(() => {
  "use strict";

  // Set to true once the /api/contact endpoint exists.
  const BACKEND_READY = false;
  const MIN_FILL_MS = 3000;          // time trap: humans need > 3 s
  const STORAGE = {
    get(k) { try { return JSON.parse(localStorage.getItem(k)); } catch { return null; } },
    set(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch { /* storage blocked: fine */ } }
  };
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const $ = (s, root = document) => root.querySelector(s);
  const $$ = (s, root = document) => Array.from(root.querySelectorAll(s));

  /* ── Year ─────────────────────────────────────────────────────── */
  const y = $("#year"); if (y) y.textContent = String(new Date().getFullYear());

  /* ── 1. Language ─────────────────────────────────────────────────
     Each language is a static page (/, /fi/, /es/) generated by
     tools/build-i18n.mjs, so search engines index every language.
     JS only needs the short dynamic messages (validation, status). */
  const lang = document.documentElement.lang || "en";
  const msgs = window.MESSAGES || {};
  const domText = {};
  $$("[data-i18n]").forEach(n => { domText[n.dataset.i18n] = n.textContent; });

  const t = (key, vars = {}) => {
    const s = (msgs[lang] && msgs[lang][key]) ?? domText[key] ?? (msgs.en && msgs.en[key]) ?? key;
    return s.replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ""));
  };

  /* ── Mobile navigation ────────────────────────────────────────── */
  const toggle = $(".nav-toggle"), nav = $("#primary-nav");
  if (toggle && nav) {
    const setOpen = open => {
      nav.classList.toggle("is-open", open);
      toggle.setAttribute("aria-expanded", String(open));
      $("span", toggle).textContent = open ? t("js.menuClose") : t("nav.menu");
    };
    toggle.addEventListener("click", () => setOpen(!nav.classList.contains("is-open")));
    nav.addEventListener("click", e => { if (e.target.closest("a")) setOpen(false); });
    document.addEventListener("keydown", e => {
      if (e.key === "Escape" && nav.classList.contains("is-open")) { setOpen(false); toggle.focus(); }
    });
  }

  /* ── 2. Systems accordion (enhances native <details>) ─────────── */
  const rows = $$(".system-row");
  const DURATION = 180;

  function animateRow(row, open) {
    const body = $(".row-body", row);
    if (row._anim) row._anim.cancel();
    if (reduceMotion || !body.animate) { row.open = open; return; }
    if (open) {
      row.open = true;
      const h = body.scrollHeight;
      row._anim = body.animate([{ height: "0px", opacity: 0 }, { height: h + "px", opacity: 1 }],
        { duration: DURATION, easing: "cubic-bezier(.2,.6,.2,1)" });
    } else {
      const h = body.scrollHeight;
      row._anim = body.animate([{ height: h + "px", opacity: 1 }, { height: "0px", opacity: 0 }],
        { duration: DURATION, easing: "cubic-bezier(.2,.6,.2,1)", fill: "forwards" });
      row._anim.onfinish = () => { row.open = false; row._anim.cancel(); row._anim = null; };
    }
  }
  rows.forEach(row => {
    $("summary", row).addEventListener("click", e => {
      e.preventDefault();
      const willOpen = !row.open;
      if (willOpen) rows.forEach(r => { if (r !== row && r.open) animateRow(r, false); }); // one open at a time
      animateRow(row, willOpen);
    });
  });

  /* ── ISO 6346 container-code validator (hero demo) ────────────── */
  const ISO_VALUES = (() => {
    const map = {}; let v = 10;
    for (let c = 65; c <= 90; c++) { if (v % 11 === 0) v++; map[String.fromCharCode(c)] = v++; }
    return map;
  })();
  function iso6346(code) {
    const s = code.toUpperCase().replace(/[\s-]/g, "");
    if (!/^[A-Z]{3}[UJZ]\d{7}$/.test(s)) return { ok: false, reason: "format" };
    let sum = 0;
    for (let i = 0; i < 10; i++) {
      const ch = s[i];
      const val = /\d/.test(ch) ? Number(ch) : ISO_VALUES[ch];
      sum += val * (2 ** i);
    }
    const expected = (sum % 11) % 10;
    const given = Number(s[10]);
    return { ok: expected === given, expected, given, reason: expected === given ? null : "digit" };
  }
  const isoForm = $("#iso-check"), isoInput = $("#iso-input"), isoOut = $("#iso-result");
  function renderIso() {
    if (!isoInput.value.trim()) { isoOut.textContent = ""; isoOut.className = "iso-result mono"; return; }
    const r = iso6346(isoInput.value);
    isoOut.className = "iso-result mono " + (r.ok ? "ok" : "err");
    isoOut.textContent = r.ok ? t("js.isoOk", { d: r.expected })
      : r.reason === "format" ? t("js.isoFormat")
      : t("js.isoBadDigit", { d: r.expected, g: r.given });
    isoInput.setAttribute("aria-invalid", String(!r.ok));
  }
  if (isoForm) {
    isoForm.addEventListener("submit", e => { e.preventDefault(); renderIso(); });
    isoInput.addEventListener("input", () => { isoInput.value = isoInput.value.toUpperCase().replace(/[^A-Z0-9]/g, ""); });
    document.addEventListener("langchange", () => { if (isoOut.textContent) renderIso(); });
  }

  /* ── 3. Contact form: validation · honeypot · time trap ──────── */
  const form = $("#contact-form");
  if (form) {
    const email = $("#cf-email"), brief = $("#cf-brief"), consent = $("#cf-consent");
    const hp = $("#cf-website"), ts = $("#cf-ts"), status = $("#cf-status"), count = $("#cf-count");
    const started = Date.now();
    ts.value = String(started);

    const EMAIL_RE = /^[^\s@<>()[\]\\,;:"]+@[^\s@<>()[\]\\,;:"]+\.[A-Za-z]{2,}$/;
    const errs = { email: null, brief: null, consent: null };

    const setError = (input, errEl, key) => {
      errs[input.id] = key;
      errEl.textContent = key ? t(key) : "";
      input.setAttribute("aria-invalid", key ? "true" : "false");
    };
    const checkEmail = () => setError(email, $("#cf-email-err"), EMAIL_RE.test(email.value.trim()) && email.value.length <= 254 ? null : "js.emailInvalid");
    const checkBrief = () => setError(brief, $("#cf-brief-err"), brief.value.trim().length >= 20 ? null : "js.briefShort");
    const checkConsent = () => setError(consent, $("#cf-consent-err"), consent.checked ? null : "js.consentRequired");

    brief.addEventListener("input", () => { count.textContent = `${brief.value.length} / 4000`; if (errs["cf-brief"]) checkBrief(); });
    email.addEventListener("blur", () => { if (email.value) checkEmail(); });
    consent.addEventListener("change", () => { if (errs["cf-consent"]) checkConsent(); });
    document.addEventListener("langchange", () => {
      [[email, "#cf-email-err"], [brief, "#cf-brief-err"], [consent, "#cf-consent-err"]].forEach(([i, sel]) => {
        if (errs[i.id]) $(sel).textContent = t(errs[i.id]);
      });
      if (status.dataset.key) status.textContent = t(status.dataset.key);
    });

    const setStatus = (key, cls) => { status.dataset.key = key; status.textContent = t(key); status.className = "form-status mono " + (cls || ""); };

    form.addEventListener("submit", async e => {
      e.preventDefault();
      checkEmail(); checkBrief(); checkConsent();
      const firstInvalid = [email, brief, consent].find(i => i.getAttribute("aria-invalid") === "true");
      if (firstInvalid) { firstInvalid.focus(); return; }

      // Bot heuristics: pretend success, send nothing.
      if (hp.value !== "" || Date.now() - started < MIN_FILL_MS) { setStatus("js.sent", "ok"); form.reset(); return; }

      if (!BACKEND_READY) { setStatus("js.prototype", "ok"); return; }

      const submitBtn = $("button[type=submit]", form);
      submitBtn.disabled = true; setStatus("js.sending");
      try {
        // JSON body; the server re-validates (schema + length), strips markup and
        // escapes on output. Never trust this client-side check.
        const res = await fetch(form.action, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          credentials: "same-origin",
          body: JSON.stringify({
            email: email.value.trim(),
            briefing: brief.value.trim(),
            privacy_consent: consent.checked,
            company_website: hp.value,
            form_ts: ts.value,
            lang
          })
        });
        if (!res.ok) throw new Error(String(res.status));
        setStatus("js.sent", "ok"); form.reset(); count.textContent = "0 / 4000";
      } catch {
        setStatus("js.error", "err");
      } finally {
        submitBtn.disabled = false;
      }
    });
  }

  /* ── Cookie consent (Traficom: equal choice, re-openable) ─────── */
  const CONSENT_KEY = "consent.v1";
  const banner = $("#cookie-banner"), dialog = $("#cookie-dialog"), cAnalytics = $("#c-analytics");

  function applyConsent(c) {
    // Load optional services ONLY after opt-in. Example (cookieless, EU-hosted):
    // if (c.analytics) { const s = document.createElement("script"); s.defer = true;
    //   s.src = "/js/analytics.js"; document.head.appendChild(s); }
    document.documentElement.dataset.analytics = c.analytics ? "on" : "off";
  }
  function saveConsent(analytics) {
    const c = { analytics: !!analytics, ts: new Date().toISOString(), v: 1 };
    STORAGE.set(CONSENT_KEY, c);
    banner.hidden = true;
    applyConsent(c);
  }
  function openSettings() {
    const c = STORAGE.get(CONSENT_KEY);
    cAnalytics.checked = !!(c && c.analytics);
    if (typeof dialog.showModal === "function") dialog.showModal();
  }

  // WCAG 2.4.11: expose the banner height so focused elements scroll clear of it
  const syncBannerHeight = () => {
    const h = banner.hidden ? 0 : Math.ceil(banner.getBoundingClientRect().height + 16);
    document.documentElement.style.setProperty("--banner-h", h + "px"); // CSSOM — allowed by CSP
  };
  if ("ResizeObserver" in window) new ResizeObserver(syncBannerHeight).observe(banner);
  new MutationObserver(syncBannerHeight).observe(banner, { attributes: true, attributeFilter: ["hidden"] });

  // WCAG 2.4.11 fallback for browsers that ignore scroll-padding on focus:
  // nudge the page so the focused element is never hidden under the sticky
  // header or the cookie banner.
  const header = $(".site-header");
  document.addEventListener("focusin", e => {
    const el = e.target;
    if (!(el instanceof Element) || el.closest(".site-header, .cookie-banner, dialog")) return;
    const r = el.getBoundingClientRect();
    const top = header ? header.getBoundingClientRect().bottom + 8 : 0;
    const bottom = banner.hidden ? window.innerHeight - 8 : banner.getBoundingClientRect().top - 8;
    if (r.bottom > bottom) window.scrollBy({ top: r.bottom - bottom, behavior: "instant" });
    else if (r.top < top) window.scrollBy({ top: r.top - top, behavior: "instant" });
  });

  const existing = STORAGE.get(CONSENT_KEY);
  if (existing && existing.v === 1) applyConsent(existing); else banner.hidden = false;

  banner.addEventListener("click", e => {
    const b = e.target.closest("[data-consent]"); if (!b) return;
    if (b.dataset.consent === "accept") saveConsent(true);
    else if (b.dataset.consent === "reject") saveConsent(false);
    else openSettings();
  });
  dialog.addEventListener("close", () => { if (dialog.returnValue === "save") saveConsent(cAnalytics.checked); });
  $$("[data-open-cookie-settings]").forEach(b => b.addEventListener("click", openSettings));

  /* ── Print: expand every accordion so nothing is lost on paper ── */
  let openedForPrint = [];
  window.addEventListener("beforeprint", () => {
    openedForPrint = rows.filter(r => !r.open);
    openedForPrint.forEach(r => { r.open = true; });
  });
  window.addEventListener("afterprint", () => {
    openedForPrint.forEach(r => { r.open = false; });
    openedForPrint = [];
  });
})();
