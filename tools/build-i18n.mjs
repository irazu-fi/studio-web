#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════
   build-i18n — renders one static, indexable page per language.

   Source of truth:  index.html (EN content)  +  assets/js/i18n.js (FI, ES…)
   Outputs:          index.html (SEO head + switcher refreshed, idempotent)
                     fi/index.html, es/index.html
                     assets/js/messages.js  (js.* keys only, loaded at runtime)
                     sitemap.xml            (with hreflang alternates)

   Usage:  node tools/build-i18n.mjs
   No dependencies. Replaced by Astro i18n routes in phase 2.
   ═══════════════════════════════════════════════════════════════ */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE_URL = "https://irazu.fi";          // no trailing slash
const LANGS = [                                       // first = default (served at /)
  { code: "en", dir: "",    label: "EN", name: "English", ogLocale: "en_GB" },
  { code: "fi", dir: "fi/", label: "FI", name: "Suomi",   ogLocale: "fi_FI" },
  { code: "es", dir: "es/", label: "ES", name: "Español", ogLocale: "es_ES" },
];

const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");
const write = (f, s) => { fs.mkdirSync(path.dirname(path.join(ROOT, f)), { recursive: true }); fs.writeFileSync(path.join(ROOT, f), s); };
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escAttr = s => esc(s).replace(/"/g, "&quot;");
const unesc = s => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&amp;/g, "&");

// Load dictionaries
const sandbox = { window: {} };
vm.runInNewContext(read("assets/js/i18n.js"), sandbox);
const DICT = sandbox.window.I18N;

const source = read("index.html");

// EN values come from the HTML itself
const EN_TEXT = {};
for (const m of source.matchAll(/<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>([^<]*)<\/\1>/g)) EN_TEXT[m[2]] = unesc(m[3]);
const EN_LABEL = {};
for (const m of source.matchAll(/aria-label="([^"]*)"[^>]*?data-i18n-label="([^"]+)"/g)) EN_LABEL[m[2]] = unesc(m[1]);
const EN_ALT = {};
for (const m of source.matchAll(/\salt="([^"]*)"[^>]*?data-i18n-alt="([^"]+)"/g)) EN_ALT[m[2]] = unesc(m[1]);
if ((source.match(/\sdata-i18n-alt="/g) || []).length !== Object.keys(EN_ALT).length) {
  throw new Error("Every data-i18n-alt needs an alt=\"…\" before it on the same <img>, with a unique key.");
}

const totalKeys = (source.match(/\sdata-i18n="/g) || []).length;
if (Object.keys(EN_TEXT).length === 0 || [...source.matchAll(/<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>([^<]*)<\/\1>/g)].length !== totalKeys) {
  throw new Error("Some data-i18n elements contain markup — data-i18n must wrap plain text only.");
}

const tr = (code, key, fallback) => (DICT[code] && DICT[code][key]) ?? (DICT.en && DICT.en[key]) ?? fallback;
const urlFor = l => `${SITE_URL}/${l.dir}`;

function seoHead(L) {
  const title = tr(L.code, "meta.title", "Irazu");
  const desc = tr(L.code, "meta.description", "");
  const alt = tr(L.code, "og.imageAlt", title);
  const og = `${SITE_URL}/assets/og/og-${L.code}.png`;
  const jsonld = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "ProfessionalService",
        "@id": `${SITE_URL}/#organization`,
        name: "Irazu",
        alternateName: "IRAZU Systems Atelier",
        url: `${SITE_URL}/`,
        logo: `${SITE_URL}/assets/brand/irazu-logo.png`,
        image: `${SITE_URL}/assets/og/og-en.png`,
        email: "hello@irazu.fi",
        description: tr("en", "meta.description", ""),
        address: { "@type": "PostalAddress", addressLocality: "Helsinki", addressCountry: "FI" },
        identifier: { "@type": "PropertyValue", propertyID: "Y-tunnus", value: "XXXXXXX-X" },
        areaServed: ["FI", "EU"],
        knowsLanguage: LANGS.map(l => l.code),
        knowsAbout: [
          "Terminal operating system (TOS)", "Container terminal software", "Gate and yard management",
          "Reefer stowage planning", "Refrigerated cargo logistics", "Customs manifests",
          "Custom software development", "E-commerce platforms"
        ]
      },
      {
        "@type": "WebSite",
        "@id": `${SITE_URL}/#website`,
        url: `${SITE_URL}/`,
        name: "Irazu",
        inLanguage: LANGS.map(l => l.code),
        publisher: { "@id": `${SITE_URL}/#organization` }
      },
      {
        "@type": "WebPage",
        "@id": `${urlFor(L)}#webpage`,
        url: urlFor(L),
        name: title,
        description: desc,
        inLanguage: L.code,
        isPartOf: { "@id": `${SITE_URL}/#website` },
        about: { "@id": `${SITE_URL}/#organization` }
      }
    ]
  };
  const p = L.dir ? "../" : "";
  return [
    `  <!-- seo:start (generated by tools/build-i18n.mjs — edit SEO text in assets/js/i18n.js) -->`,
    `  <title>${esc(title)}</title>`,
    `  <meta name="description" content="${escAttr(desc)}">`,
    `  <meta name="robots" content="index, follow, max-image-preview:large">`,
    `  <link rel="canonical" href="${urlFor(L)}">`,
    ...LANGS.map(l => `  <link rel="alternate" hreflang="${l.code}" href="${urlFor(l)}">`),
    `  <link rel="alternate" hreflang="x-default" href="${urlFor(LANGS[0])}">`,
    `  <meta name="theme-color" content="#F8F8F6">`,
    `  <link rel="apple-touch-icon" href="${p}assets/apple-touch-icon.png">`,
    `  <meta property="og:type" content="website">`,
    `  <meta property="og:site_name" content="Irazu">`,
    `  <meta property="og:title" content="${escAttr(title)}">`,
    `  <meta property="og:description" content="${escAttr(desc)}">`,
    `  <meta property="og:url" content="${urlFor(L)}">`,
    `  <meta property="og:image" content="${og}">`,
    `  <meta property="og:image:width" content="1200">`,
    `  <meta property="og:image:height" content="630">`,
    `  <meta property="og:image:alt" content="${escAttr(alt)}">`,
    `  <meta property="og:locale" content="${L.ogLocale}">`,
    ...LANGS.filter(l => l !== L).map(l => `  <meta property="og:locale:alternate" content="${l.ogLocale}">`),
    `  <meta name="twitter:card" content="summary_large_image">`,
    // JSON-LD is a data block, not executed — allowed under script-src 'self'.
    `  <script type="application/ld+json">${JSON.stringify(jsonld).replace(/</g, "\\u003c")}</script>`,
    `  <!-- seo:end -->`
  ].join("\n");
}

function langSwitch(L) {
  const p = L.dir ? "../" : "";
  const items = LANGS.map(l => {
    const href = `${p}${l.dir}index.html`;
    const cur = l === L ? ` aria-current="page"` : "";
    return `        <a href="${href}" hreflang="${l.code}" lang="${l.code}"${cur}>${l.label}<span class="visually-hidden"> ${esc(l.name)}</span></a>`;
  }).join(`\n        <span aria-hidden="true">|</span>\n`);
  const groupLabel = tr(L.code, "a11y.language", "Language");
  return `      <!-- lang:start -->
      <nav class="lang-switch" aria-label="${escAttr(groupLabel)}">
        <span aria-hidden="true">[</span>
${items}
        <span aria-hidden="true">]</span>
      </nav>
      <!-- lang:end -->`;
}

function render(L) {
  let html = source;
  html = html.replace(/<html lang="[^"]*">/, `<html lang="${L.code}">`);
  html = html.replace(/  <!-- seo:start[\s\S]*?<!-- seo:end -->/, seoHead(L));
  html = html.replace(/      <!-- lang:start -->[\s\S]*?<!-- lang:end -->/, langSwitch(L));
  if (L.code !== "en") {
    html = html.replace(/(<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([^<]*)(<\/\2>)/g,
      (all, open, tag, key, text, close) => open + esc(tr(L.code, key, EN_TEXT[key])) + close);
    html = html.replace(/aria-label="([^"]*)"([^>]*?)data-i18n-label="([^"]+)"/g,
      (all, val, mid, key) => `aria-label="${escAttr(tr(L.code, key, EN_LABEL[key]))}"${mid}data-i18n-label="${key}"`);
    html = html.replace(/\salt="([^"]*)"([^>]*?)data-i18n-alt="([^"]+)"/g,
      (all, val, mid, key) => ` alt="${escAttr(tr(L.code, key, EN_ALT[key]))}"${mid}data-i18n-alt="${key}"`);
    // Relative paths one level down. privacy.html and legal.html exist in every language
    // folder (fi/, es/), so those links stay relative to the language folder.
    html = html.replace(/(href|src)="(assets\/)/g, '$1="../$2');
    // In Finnish the "(Tietosuojaseloste)" / "(Käyttöehdot)" hints would repeat the link text.
    if (L.code === "fi") html = html.replace(/ <span lang="fi">\((Tietosuojaseloste|Käyttöehdot)\)<\/span>/g, "");
    html = html.replace(/srcset="([^"]*)"/g, (all, v) => `srcset="${v.replace(/(^|,\s*)assets\//g, "$1../assets/")}"`);
  }
  return html;
}

for (const L of LANGS) write(`${L.dir}index.html`, render(L));

// Runtime messages: only the js.* keys, all languages (~3 KB instead of the full dictionary)
const messages = {};
for (const L of LANGS) {
  messages[L.code] = Object.fromEntries(Object.entries(DICT[L.code] || {}).filter(([k]) => k.startsWith("js.") || k === "nav.menu"));
}
messages.en["nav.menu"] = messages.en["nav.menu"] ?? EN_TEXT["nav.menu"];
write("assets/js/messages.js",
  `/* Generated by tools/build-i18n.mjs — do not edit. Source: assets/js/i18n.js */\nwindow.MESSAGES = ${JSON.stringify(messages, null, 2)};\n`);

// Sitemap with hreflang alternates
const today = new Date().toISOString().slice(0, 10);
const alts = LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l.code}" href="${urlFor(l)}"/>`).join("\n")
  + `\n    <xhtml:link rel="alternate" hreflang="x-default" href="${urlFor(LANGS[0])}"/>`;
write("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${LANGS.map(l => `  <url>\n    <loc>${urlFor(l)}</loc>\n    <lastmod>${today}</lastmod>\n${alts}\n  </url>`).join("\n")}
</urlset>
`);

// Report missing translations
for (const L of LANGS.slice(1)) {
  const missing = Object.keys(EN_TEXT).filter(k => !(DICT[L.code] && k in DICT[L.code]));
  const missingL = Object.keys(EN_LABEL).filter(k => !(DICT[L.code] && k in DICT[L.code]));
  const missingA = Object.keys(EN_ALT).filter(k => !(DICT[L.code] && k in DICT[L.code]));
  if (missing.length || missingL.length || missingA.length) console.warn(`[${L.code}] missing: ${[...missing, ...missingL, ...missingA].join(", ")}`);
}
console.log(`Built ${LANGS.map(l => "/" + l.dir).join(", ")} · ${Object.keys(EN_TEXT).length} text keys · sitemap.xml · messages.js`);
